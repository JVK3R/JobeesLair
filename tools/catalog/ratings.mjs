// Builds catalog/ratings.json and app/data/ratings.js: every game's PlayStation Store star rating, for the
// Top Rated lane and the rating sort (state/catalog.js). Added in 0.5.1.
//
//   node tools/catalog/ratings.mjs          (from the repository root, Node 20+)
//
// The store's catalog API names a title ID's concept with its star rating ({ score: "4.77", total: "76635" }),
// one request a game, no key. Every game the app bundles and every game the live catalog lists is asked for
// once; after that, the ratings older than STALE_DAYS are asked again, a slice a run, so the scheduled
// workflow (.github/workflows/catalog-live.yml) keeps them current without asking for all of them each time.
// The live catalog carries the ratings too (tools/catalog/live-feed.mjs), so a console has new ones without
// a new release.
import { readFileSync, writeFileSync, mkdirSync, existsSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..', '..');
const OUT = join(ROOT, 'catalog', 'ratings.json');
const BUNDLED = join(ROOT, 'app', 'data', 'ratings.js');
const API = (id) => `https://m.np.playstation.com/api/catalog/v2/titles/${id}_00/concepts?country=US&language=en&age=999`;
const STALE_DAYS = 14, REFRESH_PER_RUN = 400, WORKERS = 4;
const TITLE_ID = /^(?:CUSA|PPSA)\d{5}$/;
const DAY = 864e5;

// { id: { stars, count, at } }, or { id: { none: true, at } } for a title the store has no concept for.
const known = existsSync(OUT) ? JSON.parse(readFileSync(OUT, 'utf8')) : {};

function ids() {
  const out = new Set([...readFileSync(join(ROOT, 'app/data/catalog.js'), 'utf8').matchAll(/"id": "((?:CUSA|PPSA)\d{5})"/g)].map((m) => m[1]));
  try {
    for (const game of JSON.parse(readFileSync(join(ROOT, 'catalog/live.json'), 'utf8')).games) if (TITLE_ID.test(game.id)) out.add(game.id);
  } catch {}
  return [...out].sort();
}

async function rating(id) {
  for (let attempt = 1; attempt <= 3; attempt++) {
    try {
      const response = await fetch(API(id), { headers: { 'User-Agent': 'Mozilla/5.0', Accept: 'application/json' }, signal: AbortSignal.timeout(20000) });
      if (response.status === 429 || response.status >= 500) throw new Error(`HTTP ${response.status}`);
      const body = await response.json();
      const concept = Array.isArray(body) ? body.find((entry) => entry?.starRating || entry?.id) : null;
      if (!concept || concept.errorCode) return { none: true };
      const stars = Number(concept.starRating?.score), count = Number(concept.starRating?.total);
      if (!(stars >= 1 && stars <= 5) || !Number.isSafeInteger(count) || count <= 0) return { none: true };
      return { stars: Math.round(stars * 100) / 100, count };
    } catch (error) {
      if (attempt === 3) return null;
      await new Promise((resolve) => setTimeout(resolve, 2000 * attempt));
    }
  }
  return null;
}

async function main() {
  const now = Date.now();
  const all = ids();
  const missing = all.filter((id) => !known[id]);
  const stale = all.filter((id) => known[id] && now - known[id].at > STALE_DAYS * DAY).sort((a, b) => known[a].at - known[b].at).slice(0, REFRESH_PER_RUN);
  const queue = [...missing, ...stale];
  let asked = 0, failed = 0;
  const worker = async () => {
    while (queue.length) {
      const id = queue.shift();
      const found = await rating(id);
      asked++;
      if (found) known[id] = { ...found, at: now };
      else failed++;
    }
  };
  await Promise.all(Array.from({ length: WORKERS }, worker));

  const rated = Object.entries(known).filter(([id, entry]) => all.includes(id) && entry.count).sort(([a], [b]) => a.localeCompare(b));
  mkdirSync(dirname(OUT), { recursive: true });
  writeFileSync(OUT, `${JSON.stringify(Object.fromEntries(Object.entries(known).sort(([a], [b]) => a.localeCompare(b))))}\n`);
  // The app's copy: [stars, count] by title ID, what the console reads before any feed has come.
  const pairs = rated.map(([id, entry]) => `"${id}":[${entry.stars},${entry.count}]`).join(',');
  writeFileSync(BUNDLED, `// Generated by tools/catalog/ratings.mjs: each game's PlayStation Store star rating, [stars, ratings].\n  var ratings = {${pairs}};\n\nexport { ratings };\n`);
  console.log(`ratings: ${rated.length} of ${all.length} games rated; asked ${asked} (${missing.length} new, ${stale.length} stale), ${failed} failed`);
}

main().catch((error) => {
  console.error(error.message);
  process.exit(1);
});
