#!/usr/bin/env node
// Builds app/data/screensaver.js, the screen saver's slides (0.5.0 Pre Release 4): full-screen screenshots of
// the catalog's most popular games. Each is a link to the screenshot the game's own store page shows
// (Steam or the PlayStation Store), fetched by the console like the rest of the store's art; nothing is copied
// into the app. Every link is checked online: it must answer, be a JPEG or PNG, and be at least 1920 x 1080.
//
//   node tools/catalog/screensaver.mjs
//
// Per game, the first two screenshots that pass, from the GAMES most recommended games, up to SLIDES slides.

import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

const repo = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '../..');
const { games } = await import(pathToFileURL(path.join(repo, 'app/data/catalog.js')).href);
const GAMES = 60, PER_GAME = 2, SLIDES = 80, PARALLEL = 6;
const UA = 'JobeesLair-screensaver (+https://github.com/JVK3R/JobeesLair)';

// Width and height from a JPEG's or PNG's first bytes.
export function imageSize(bytes) {
  if (bytes[0] === 0x89 && bytes[1] === 0x50) return { width: bytes.readUInt32BE(16), height: bytes.readUInt32BE(20) };
  if (bytes[0] !== 0xff || bytes[1] !== 0xd8) return null;
  for (let at = 2; at + 9 < bytes.length;) {
    if (bytes[at] !== 0xff) return null;
    const marker = bytes[at + 1];
    const length = bytes.readUInt16BE(at + 2);
    if (marker >= 0xc0 && marker <= 0xcf && ![0xc4, 0xc8, 0xcc].includes(marker)) return { width: bytes.readUInt16BE(at + 7), height: bytes.readUInt16BE(at + 5) };
    at += 2 + length;
  }
  return null;
}

async function check(url) {
  try {
    const response = await fetch(url, { headers: { 'user-agent': UA, range: 'bytes=0-65535' } });
    if (!response.ok) return null;
    const bytes = Buffer.from(await response.arrayBuffer());
    const size = imageSize(bytes);
    return size && size.width >= 1920 && size.height >= 1080 ? size : null;
  } catch {
    return null;
  }
}

const popular = [...games].sort((a, b) => (b.recommendations ?? 0) - (a.recommendations ?? 0)).slice(0, GAMES);
const slides = [];
const queue = [...popular];
let checked = 0, kept = 0;
const found = new Map();
await Promise.all(Array.from({ length: PARALLEL }, async () => {
  for (let game; (game = queue.shift()); ) {
    let page;
    try {
      page = JSON.parse(fs.readFileSync(path.join(repo, 'app/data/pages', `${encodeURIComponent(game.id)}.json`), 'utf8'));
    } catch {
      continue;
    }
    const picks = [];
    for (const shot of page.shots ?? []) {
      if (picks.length >= PER_GAME) break;
      const url = typeof shot === 'string' ? shot : shot?.url;
      if (typeof url !== 'string' || !url.startsWith('https://')) continue;
      checked++;
      if (await check(url)) picks.push(url);
    }
    kept += picks.length;
    found.set(game.id, picks.map((url) => ({ id: game.id, title: game.title, url })));
  }
}));
// In popularity order, one game's second picture only after every game's first.
for (let round = 0; round < PER_GAME; round++) for (const game of popular) {
  const pick = found.get(game.id)?.[round];
  if (pick && slides.length < SLIDES) slides.push(pick);
}
const body = [
  '// Generated by tools/catalog/screensaver.mjs: the screen saver\'s slides, screenshots of the most popular',
  '// games from their own store pages (Steam, PlayStation Store), each checked to load at 1920 x 1080 or more.',
  '// Links only: the console fetches them like the store\'s other art. Do not edit; run the tool again.',
  '',
  '  var slides = [',
  slides.map((slide) => `    ${JSON.stringify(slide)}`).join(',\n'),
  '  ];',
  '',
  'export { slides };',
  '',
].join('\n');
fs.writeFileSync(path.join(repo, 'app/data/screensaver.js'), body);
console.log(`${slides.length} slides from ${new Set(slides.map((s) => s.id)).size} games (${checked} screenshots checked, ${kept} passed)`);
