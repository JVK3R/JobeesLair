#!/usr/bin/env node
// Builds app/data/formats.js: which kinds of download each bundled game has, so the store can filter by
// format ("Ready for 13.60", "Folder dump", ".exfat image" ...) without reading 2,000 release files on the
// console. Each game's releases (app/data/releases/<id>.json) are sorted with the rules the source picker
// uses for its 13.60 badges (app/state/release-sets.js releaseType), so the filter and the badges agree.
//
//   node tools/catalog/formats.mjs
//
// A game's kinds, in this order: folder, exfat, ffpkg, ffpfs, image (a disk image whose kind no name or
// format says), backport, fpkg. Feed releases are added on the console when the feeds load
// (app/state/catalog.js). Run it again whenever the bundled releases change; tests/app.test.mjs checks the
// file is current.

import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

const repo = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '../..');
const { gameFormats } = await import(pathToFileURL(path.join(repo, 'app/state/formats.js')).href);

export function buildFormats(dir = path.join(repo, 'app/data/releases')) {
  const formats = {};
  for (const name of fs.readdirSync(dir).filter((file) => file.endsWith('.json')).sort()) {
    const id = name.slice(0, -5);
    const platform = /^PPSA/i.test(id) ? 'ps5' : /^CUSA/i.test(id) ? 'ps4' : undefined;
    const kinds = gameFormats(JSON.parse(fs.readFileSync(path.join(dir, name), 'utf8')), platform);
    if (kinds.length) formats[id] = kinds.join(' ');
  }
  return formats;
}

export function formatsModule(formats) {
  const lines = Object.entries(formats).map(([id, kinds]) => `    ${JSON.stringify(id)}: ${JSON.stringify(kinds)}`);
  return [
    '// Generated by tools/catalog/formats.mjs from app/data/releases: the kinds of download each bundled game',
    '// has, space-separated (app/state/formats.js). Do not edit; run the tool again.',
    '',
    '  var formats = {',
    lines.join(',\n'),
    '  };',
    '',
    'export { formats };',
    '',
  ].join('\n');
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const formats = buildFormats();
  fs.writeFileSync(path.join(repo, 'app/data/formats.js'), formatsModule(formats));
  const counts = {};
  for (const kinds of Object.values(formats)) for (const kind of kinds.split(' ')) counts[kind] = (counts[kind] ?? 0) + 1;
  console.log(`${Object.keys(formats).length} games:`, counts);
}
