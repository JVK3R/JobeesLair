"""Prepares Jobee'sLair's typeface, Exo 2 (SIL Open Font License 1.1), from Google Fonts' repository:

    python3 packaging/brand/make_fonts.py     (from the repository root; needs fonttools and brotli)

- app/assets/Exo2.ttf: a static instance at weight 500 for the console, where the build bakes it into
  bitmap glyphs (bold is drawn by the renderer from it).
- app/companion/fonts.js: weights 500 and 700 as WOFF2, subset to Latin, accented European and Cyrillic,
  base64 for the phone page's @font-face (the page makes no outside requests).
- app/notices/Exo2-OFL.txt and Exo2-SOURCE.txt: the license, which must ship with the font, and where
  and what was fetched.
"""
import base64
import hashlib
import io
import urllib.request
from pathlib import Path

from fontTools import subset
from fontTools.ttLib import TTFont
from fontTools.varLib import instancer

ROOT = Path(__file__).resolve().parents[2]
APP = ROOT / "app"
BASE = "https://raw.githubusercontent.com/google/fonts/main/ofl/exo2/"
VARIABLE = BASE + "Exo2%5Bwght%5D.ttf"
LICENSE = BASE + "OFL.txt"
# Basic Latin, Latin-1, Latin Extended-A, Ș Ț, Cyrillic (with Ґ), general punctuation, arrows, € ₹ ₽ №, ○ •.
UNICODES = [*range(0x20, 0x7F), *range(0xA0, 0x180), 0x218, 0x219, 0x21A, 0x21B, *range(0x400, 0x460), 0x490, 0x491,
            *range(0x2010, 0x2028), *range(0x2030, 0x203B), 0x2039, 0x203A, 0x20AC, 0x20B9, 0x20BD, 0x2116, 0x2190, 0x2192,
            0x25CB, 0x2022]


def fetch(url):
    with urllib.request.urlopen(url, timeout=60) as response:
        return response.read()


def instance(variable_bytes, weight):
    font = TTFont(io.BytesIO(variable_bytes))
    return instancer.instantiateVariableFont(font, {"wght": weight}, inplace=False, updateFontNames=True)


def woff2(font):
    options = subset.Options()
    options.flavor = "woff2"
    options.layout_features = ["kern", "liga", "calt", "tnum"]
    options.name_IDs = ["*"]
    subsetter = subset.Subsetter(options)
    subsetter.populate(unicodes=UNICODES)
    subsetter.subset(font)
    out = io.BytesIO()
    font.flavor = "woff2"
    font.save(out)
    return out.getvalue()


def main():
    variable = fetch(VARIABLE)
    license_text = fetch(LICENSE)
    console = instance(variable, 500)
    console.save(APP / "assets/Exo2.ttf")
    phone = {weight: woff2(instance(variable, weight)) for weight in (500, 700)}
    lines = [
        "// Generated by packaging/brand/make_fonts.py: Exo 2 (SIL OFL 1.1, app/notices/Exo2-OFL.txt), weights",
        "// 500 and 700 as WOFF2 subset to Latin, accented European and Cyrillic, for the phone page's @font-face.",
        "",
    ]
    for weight, data in phone.items():
        lines.append(f'  var EXO2_{weight} = "{base64.b64encode(data).decode()}";')
    lines += ["", "export { EXO2_500, EXO2_700 };", ""]
    (APP / "companion/fonts.js").write_text("\n".join(lines), encoding="utf-8")
    notices = APP / "notices"
    notices.mkdir(exist_ok=True)
    (notices / "Exo2-OFL.txt").write_bytes(license_text)
    (notices / "Exo2-SOURCE.txt").write_text(
        "Exo 2, by Natanael Gama, from Google Fonts (SIL Open Font License 1.1, Exo2-OFL.txt).\n"
        f"{VARIABLE}\n  sha256 {hashlib.sha256(variable).hexdigest()}\n"
        f"{LICENSE}\n  sha256 {hashlib.sha256(license_text).hexdigest()}\n"
        "app/assets/Exo2.ttf is its weight-500 instance; app/companion/fonts.js holds subset WOFF2 instances\n"
        "at 500 and 700. Made with fontTools (varLib.instancer, subset).\n", encoding="utf-8")
    print(f"variable {len(variable)} bytes; Exo2.ttf {(APP / 'assets/Exo2.ttf').stat().st_size} bytes; "
          f"woff2 500: {len(phone[500])} bytes, 700: {len(phone[700])} bytes")


if __name__ == "__main__":
    main()
